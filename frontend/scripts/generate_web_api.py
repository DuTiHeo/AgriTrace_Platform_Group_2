"""Generate the web transport layer from backend OpenAPI, without calling mutations.

Run from frontend: python scripts/generate_web_api.py --schema http://127.0.0.1:8000/openapi.json
An exported local JSON file can also be supplied as --schema.
"""
import argparse
import json
import re
from collections import defaultdict
from pathlib import Path
from urllib.request import urlopen


ROOT = Path(__file__).resolve().parents[1]
METHODS = {"get", "post", "patch", "put", "delete"}


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def camel(value):
    parts = re.split(r"[_\s-]+", value)
    return parts[0][:1].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def schema_type(schema, prefix=""):
    if "$ref" in schema:
        return prefix + schema["$ref"].rsplit("/", 1)[-1]
    for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in schema:
            return "(" + separator.join(schema_type(s, prefix) for s in schema[key]) + ")"
    if "enum" in schema:
        return " | ".join(quote(value) for value in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + schema_type(schema.get("items", {}), prefix) + ">"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [f'{quote(name)}{"" if name in required else "?"}: {schema_type(value, prefix)}' for name, value in props.items()]
        additional = schema.get("additionalProperties")
        if additional is not False and not props:
            return "Record<string, " + (schema_type(additional, prefix) if isinstance(additional, dict) else "unknown") + ">"
        return "{ " + "; ".join(fields) + " }"
    if kind == "string":
        return "Blob" if schema.get("format") == "binary" else "string"
    return {"integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def generate(schema):
    target = ROOT / "src" / "sevices"
    banner = "// Generated by scripts/generate_web_api.py from backend OpenAPI. Do not edit by hand.\n"
    models = [banner, "// Dates/UUIDs remain API strings; optional and nullable fields follow the backend contract.\n"]
    for name, value in schema.get("components", {}).get("schemas", {}).items():
        models.append(f"export type {name} = {schema_type(value)};\n")
    (target / "backend_api_types_wb.ts").write_text("\n".join(models), encoding="utf-8")

    groups = defaultdict(list)
    catalog = []
    names = defaultdict(set)
    for path, row in schema["paths"].items():
        for method, operation in row.items():
            if method not in METHODS:
                continue
            group = camel(operation.get("tags", ["system"])[0])
            suffix = re.sub(r"\W", "_", path) + "_" + method
            operation_id = operation["operationId"]
            name = camel(operation_id[:-len(suffix)] if operation_id.endswith(suffix) else operation_id)
            if name in names[group]:
                name += method.capitalize()
            if name in names[group]:
                raise ValueError(f"Duplicate operation: {group}.{name}")
            names[group].add(name)
            parameters = row.get("parameters", []) + operation.get("parameters", [])
            parts = []
            required_args = False
            for location in ("path", "query"):
                params = [p for p in parameters if p["in"] == location]
                if not params:
                    continue
                required = any(p.get("required", False) for p in params)
                required_args |= required
                fields = "; ".join(f'{quote(p["name"])}{"" if p.get("required") else "?"}: {schema_type(p["schema"], "Api.")}' for p in params)
                parts.append(f'{location}{"" if required else "?"}: {{ {fields} }}')
            content = operation.get("requestBody", {}).get("content", {})
            content_type = next(iter(content), None)
            if content_type:
                required = operation["requestBody"].get("required", False)
                required_args |= required
                parts.append(f'body{"" if required else "?"}: {schema_type(content[content_type].get("schema", {}), "Api.")}')
            parts.extend(["signal?: AbortSignal", "cacheTtl?: number"])
            args = "args: { " + "; ".join(parts) + " }" + ("" if required_args else " = {}")
            response = next((v for code, v in operation.get("responses", {}).items() if str(code).startswith("2")), {})
            response_schema = response.get("content", {}).get("application/json", {}).get("schema")
            return_type = schema_type(response_schema, "Api.") if response_schema is not None else "void"
            url = re.sub(r"\{([^}]+)\}", lambda match: '${encodeURIComponent(String(args.path[' + quote(match[1]) + ']))}', path)
            query = " + apiQuery(args.query)" if any(p["in"] == "query" for p in parameters) else ""
            options = [f'authenticated: {"true" if operation.get("security") else "false"}', "signal: args.signal", "cacheTtl: args.cacheTtl"]
            if content_type == "multipart/form-data":
                body = "multipartBody(args.body)"
            elif content_type in (None, "application/json"):
                body = "args.body" if content_type else "undefined"
            else:
                raise ValueError(f"Unsupported request encoding: {content_type}")
            call = f"httpClient.{method}<{return_type}>(`{url}`{query}"
            if method in ("post", "put", "patch"):
                call += ", " + body
            elif content_type:
                options.append("body: " + body)
            call += ", { " + ", ".join(options) + " })"
            summary = operation.get("summary", "").replace("*/", "")
            description = operation.get("description", "").strip().replace("*/", "")
            comment = f"  /** {method.upper()} {path} — {summary}"
            if description:
                comment += "\n" + "\n".join("   * " + line for line in description.splitlines())
            comment += "\n   */"
            groups[group].append(f"{comment}\n  {name}: ({args}): Promise<{return_type}> =>\n    {call},")
            catalog.append((group, name, method.upper(), path, bool(operation.get("security")), content_type))

    helpers = '''import { httpClient } from "./httpClient_wb";
import type * as Api from "./backend_api_types_wb";

function apiQuery(query?: object): string {
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query ?? {})) {
    if (value === undefined || value === null) continue;
    for (const item of Array.isArray(value) ? value : [value]) params.append(key, String(item));
  }
  return params.size ? `?${params}` : "";
}

function multipartBody(body: object): FormData {
  const form = new FormData();
  for (const [key, value] of Object.entries(body)) {
    if (value === undefined || value === null) continue;
    for (const item of Array.isArray(value) ? value : [value]) {
      form.append(key, item instanceof Blob ? item : String(item));
    }
  }
  return form;
}

// Importing this module does not send requests. Backend enforces roles on each call.
export const webApi = {
'''
    code = banner + helpers
    for group, operations in groups.items():
        code += f"  {group}: {{\n" + "\n".join("  " + line for operation in operations for line in operation.splitlines()) + "\n  },\n"
    code += "};\n"
    (target / "webApi_wb.ts").write_text(code, encoding="utf-8")
    docs = ["# Danh mục API web", "", "Tự sinh từ OpenAPI bằng `frontend/scripts/generate_web_api.py`. Mọi hàm nằm trong `webApi_wb.ts`, dùng token và cấu hình của `httpClient_wb.ts`. Import không tự gửi request. Backend quyết định quyền; có hàm không có nghĩa Owner được dùng mọi thao tác Admin.", "", "| Hàm | Method | Endpoint | Đăng nhập |", "| --- | --- | --- | --- |"]
    docs += [f'| `webApi.{group}.{name}` | {method} | `{path}` | {"Có" if authenticated else "Không"} |' for group, name, method, path, authenticated, _ in catalog]
    (target / "WEB_API_CATALOG.md").write_text("\n".join(docs) + "\n", encoding="utf-8")
    print(f"Generated {len(catalog)} operations in {len(groups)} groups and {len(schema['components']['schemas'])} DTO types.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", default="http://127.0.0.1:8000/openapi.json")
    args = parser.parse_args()
    if args.schema.startswith(("https://", "http://")):
        with urlopen(args.schema, timeout=15) as response:
            schema = json.load(response)
    else:
        schema = json.loads(Path(args.schema).read_text(encoding="utf-8-sig"))
    generate(schema)
